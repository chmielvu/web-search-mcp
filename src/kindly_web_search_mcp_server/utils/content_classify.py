"""Status classification for extracted page content.

Moved from ``content/sanitize.py`` with four behavior changes:
- ``_normalize`` applies NFKC before phrase matching (mojibake-proofing).
- Typed-JSON skips carry ``cacheable=False`` on error HTTP statuses (a 404
  JSON body is valid JSON but must not poison the page cache).
- Gopher-style junk ratios (datatrove) feed a ``partial`` verdict.
- ``wall_from_classification`` consumes a ``ClassificationResult`` — the
  caller classifies once; no internal re-classification.
"""

